std::string bytes(const unsigned char (&a)[N]) {
  return std::string(reinterpret_cast<const char*>(a), N);
}

const std::string kHello = "Hello, popso! Hello, popso! 12345\n";

std::string mps_text() {
  std::string s = "NAME test\nROWS\n N obj\n";
  for (int i = 0; i < 60; ++i) s += " L c" + std::to_string(i) + "\n";
  s += "COLUMNS\n";
  for (int j = 0; j < 120; ++j)
    s += "    x" + std::to_string(j) + " c" + std::to_string((j * 7) % 60) + " " + std::to_string(j % 9 + 1) + "\n";
  return s + "ENDATA\n";
}

std::string big_payload() {
  std::string s;
  for (int i = 0; i < 25000; ++i) s += "row R" + std::to_string(i % 20) + " col C" + std::to_string(i % 13) + "\n";
  return s;
}

int first_block_type(const std::string& g) { return (static_cast<unsigned char>(g[10]) >> 1) & 3; }

// A gzip stream of stored blocks (at most 65535 bytes each), written here.
std::string stored_gzip(const std::string& data) {
  std::string g = {'\x1f', '\x8b', '\x08', '\0', '\0', '\0', '\0', '\0', '\0', '\x03'};
  size_t pos = 0;
  do {
    const size_t n = std::min<size_t>(65535, data.size() - pos);
    const bool last = pos + n == data.size();
    g += static_cast<char>(last ? 1 : 0);
    g += static_cast<char>(n & 0xFF);
    g += static_cast<char>(n >> 8);
    g += static_cast<char>(~n & 0xFF);
    g += static_cast<char>((~n >> 8) & 0xFF);
    g.append(data, pos, n);
    pos += n;
  } while (pos < data.size());
  const uint32_t crc = crc32_update(0, reinterpret_cast<const unsigned char*>(data.data()), data.size());
  const uint32_t len = static_cast<uint32_t>(data.size());
  for (int k = 0; k < 4; ++k) g += static_cast<char>((crc >> (8 * k)) & 0xFF);
  for (int k = 0; k < 4; ++k) g += static_cast<char>((len >> (8 * k)) & 0xFF);
  return g;
}

// A high-ratio stream ("gzip bomb"), written here: one fixed-Huffman block with the literal 'a' and
// `copies` matches of length 258 at distance 1 (13 bits each), so 1 + 258 * copies bytes of 'a'
// from about 1.6 bytes per copy.
std::string bomb_gzip(size_t copies) {
  std::string g = {'\x1f', '\x8b', '\x08', '\0', '\0', '\0', '\0', '\0', '\0', '\x03'};
  uint32_t acc = 0;
  int nbits = 0;
  const auto bits = [&](uint32_t v, int n) {  // LSB first
    acc |= v << nbits;
    nbits += n;
    while (nbits >= 8) {
      g += static_cast<char>(acc & 0xFF);
      acc >>= 8;
      nbits -= 8;
    }
  };
  const auto code = [&](uint32_t c, int n) {  // Huffman codes go MSB first
    for (int k = n - 1; k >= 0; --k) bits((c >> k) & 1, 1);
  };
  bits(1, 1);              // BFINAL
  bits(1, 2);              // BTYPE 01: fixed Huffman
  code(0x30 + 'a', 8);     // literal 'a'
  for (size_t k = 0; k < copies; ++k) {
    code(0xC0 + 5, 8);     // length code 285: 258
    code(0, 5);            // distance code 0: 1
  }
  code(0, 7);  // end of block
  if (nbits > 0) bits(0, 8 - nbits);
  const std::string data(1 + 258 * copies, 'a');
  const uint32_t crc = crc32_update(0, reinterpret_cast<const unsigned char*>(data.data()), data.size());
  const uint32_t len = static_cast<uint32_t>(data.size());
  for (int k = 0; k < 4; ++k) g += static_cast<char>((crc >> (8 * k)) & 0xFF);
  for (int k = 0; k < 4; ++k) g += static_cast<char>((len >> (8 * k)) & 0xFF);
  return g;
}

bool throws_gzip_error(const std::string& g) {
  try {
    gunzip(g);
  } catch (const GzipError&) {
    return true;
  }
  return false;
}

// Decompresses with a source that hands out `chunk` bytes at a time (streaming input) and a sink
// that records the pieces.
std::string gunzip_chunked(const std::string& g, size_t chunk, size_t* pieces) {
  size_t pos = 0;
  std::string out;
  *pieces = 0;
  gunzip(
      [&](unsigned char* buf, size_t cap) {
        const size_t n = std::min({cap, chunk, g.size() - pos});
        std::copy(g.begin() + static_cast<std::ptrdiff_t>(pos), g.begin() + static_cast<std::ptrdiff_t>(pos + n), buf);
        pos += n;
        return n;
      },
      [&](const char* d, size_t n) {
        out.append(d, n);
        ++*pieces;
      });
  return out;
}

void write_file(const std::filesystem::path& p, const std::string& data) {
  std::FILE* f = std::fopen(p.string().c_str(), "wb");
  REQUIRE(f != nullptr);
  std::fwrite(data.data(), 1, data.size(), f);
  std::fclose(f);
}

