TEST(gzip_crc32) {
  CHECK(crc32_update(0, reinterpret_cast<const unsigned char*>(kHello.data()), kHello.size()) == 0x61f905cdu);
  const std::string s = "123456789";  // the standard check value
  CHECK(crc32_update(0, reinterpret_cast<const unsigned char*>(s.data()), s.size()) == 0xCBF43926u);
  // Incremental.
  const uint32_t a = crc32_update(0, reinterpret_cast<const unsigned char*>(s.data()), 4);
  CHECK(crc32_update(a, reinterpret_cast<const unsigned char*>(s.data()) + 4, 5) == 0xCBF43926u);
}

TEST(gzip_block_types) {
  CHECK(first_block_type(bytes(k_stored)) == 0);
  CHECK(first_block_type(bytes(k_fixed)) == 1);
  CHECK(first_block_type(bytes(k_fixed_level1)) == 1);
  CHECK(first_block_type(bytes(k_dynamic)) == 2);
  CHECK(first_block_type(bytes(k_big_dynamic)) == 2);
  CHECK(first_block_type(bytes(k_big_huffman_only)) == 2);
  CHECK(gunzip(bytes(k_stored)) == kHello);
  CHECK(gunzip(bytes(k_fixed)) == kHello);
  CHECK(gunzip(bytes(k_fixed_level1)) == "abcabcabcabcabcabc");
  CHECK(gunzip(bytes(k_dynamic)) == mps_text());
  CHECK(gunzip(bytes(k_empty)).empty());
  CHECK(gunzip(bytes(k_two_members)) == "first member\nsecond member\n");
  CHECK(gunzip(bytes(k_header_flags)) == kHello);
  const std::string big = big_payload();
  CHECK(gunzip(bytes(k_big_dynamic)) == big);  // 368 KB: back references across the window slides
  CHECK(gunzip(bytes(k_big_huffman_only)) == big.substr(0, 3000));
}

TEST(gzip_streaming_and_stored_blocks) {
  const std::string big = big_payload();
  // Input one byte at a time and in odd chunks; the output arrives in several pieces.
  for (size_t chunk : {size_t{1}, size_t{7}, size_t{4096}}) {
    size_t pieces = 0;
    CHECK(gunzip_chunked(bytes(k_big_dynamic), chunk, &pieces) == big);
    CHECK(pieces >= 2);
    CHECK(gunzip_chunked(bytes(k_two_members), chunk, &pieces) == "first member\nsecond member\n");
  }
  // Stored blocks of 65535 bytes (several blocks, LEN / NLEN), and an empty stored block.
  const std::string data = big + big.substr(0, 1234);
  const std::string g = stored_gzip(data);
  CHECK(gunzip(g) == data);
  CHECK(gunzip(stored_gzip("")).empty());
  // Zero padding after the last member is tolerated.
  CHECK(gunzip(bytes(k_fixed) + std::string(5, '\0')) == kHello);
}

TEST(gzip_corrupt_data) {
  const std::string good = bytes(k_dynamic);
  CHECK(!throws_gzip_error(good));
  // CRC-32 and length in the trailer.
  std::string bad_crc = good;
  bad_crc[bad_crc.size() - 8] ^= 1;
  CHECK(throws_gzip_error(bad_crc));
  std::string bad_len = good;
  bad_len[bad_len.size() - 1] ^= 1;
  CHECK(throws_gzip_error(bad_len));
  // A flipped bit in the compressed data (a different code, distance or CRC).
  int caught = 0;
  for (size_t k = 12; k + 8 < good.size(); k += 37) {
    std::string b = good;
    b[k] ^= 0x10;
    caught += throws_gzip_error(b);
  }
  CHECK(caught >= 15);
  // Truncated at every length.
  bool all_truncations = true;
  for (size_t n = 0; n < good.size(); n += 13) all_truncations = all_truncations && throws_gzip_error(good.substr(0, n));
  CHECK(all_truncations);
  CHECK(throws_gzip_error(good.substr(0, good.size() - 1)));
  // Bad magic, method, reserved flags, block type 3, stored LEN / NLEN, trailing garbage.
  std::string b = good;
  b[1] = 0x00;
  CHECK(throws_gzip_error(b));
  b = good;
  b[2] = 7;
  CHECK(throws_gzip_error(b));
  b = good;
  b[3] = static_cast<char>(0x20);
  CHECK(throws_gzip_error(b));
  b = bytes(k_fixed);
  b[10] = static_cast<char>(b[10] | 0x06);
  CHECK(throws_gzip_error(b));
  b = bytes(k_stored);
  b[13] ^= 1;
  CHECK(throws_gzip_error(b));
  CHECK(throws_gzip_error(bytes(k_fixed) + "xyz"));
  CHECK(throws_gzip_error("plain text, not gzip"));
}

TEST(gzip_model_files) {
  const auto dir = std::filesystem::temp_directory_path();
  const std::string text = mps_text();
  const Model plain = read_mps_string(text);
  // .mps.gz, and gzip data under a plain .mps name (detected by the magic bytes).
  for (const char* name : {"milp_test_gzip.mps.gz", "milp_test_gzip_noext.mps"}) {
    const auto p = dir / name;
    write_file(p, bytes(k_dynamic));
    const Model m = read_mps(p.string());
    CHECK(m.num_rows() == plain.num_rows() && m.num_cols() == plain.num_cols() && m.num_nonzeros() == plain.num_nonzeros());
    CHECK(m.col_names == plain.col_names);
    std::filesystem::remove(p);
  }
  // LP format (stored blocks written here).
  const std::string lp = "Minimize\n obj: x + 2 y\nSubject To\n c1: x + y >= 3\nEnd\n";
  const auto pl = dir / "milp_test_gzip.lp.gz";
  write_file(pl, stored_gzip(lp));
  const Model m = read_lp(pl.string());
  CHECK(m.num_rows() == 1 && m.num_cols() == 2);
  std::filesystem::remove(pl);
  // A corrupt file names the path in the error.
  const auto pc = dir / "milp_test_gzip_bad.mps.gz";
  std::string bad = bytes(k_dynamic);
  bad[bad.size() - 6] ^= 0x40;
  write_file(pc, bad);
  bool caught = false;
  try {
    read_mps(pc.string());
  } catch (const MpsError& e) {
    caught = std::string(e.what()).find("milp_test_gzip_bad") != std::string::npos;
  }
  CHECK(caught);
  std::filesystem::remove(pc);
  // Uncompressed files still read as before.
  const auto pp = dir / "milp_test_plain.mps";
  write_file(pp, text);
  CHECK(read_mps(pp.string()).num_cols() == plain.num_cols());
  std::filesystem::remove(pp);
}

TEST(gzip_output_limit) {
  // About 6.7 KB expanding to 1 MB + 1 KB (ratio ~158).
  const size_t copies = 4100;
  const std::string g = bomb_gzip(copies);
  const size_t out = 1 + 258 * copies;
  CHECK(g.size() < 7000);
  CHECK(gzip_max_output() == kDefaultGzipMaxOutput);
  CHECK(gunzip(g) == std::string(out, 'a'));
  CHECK(gunzip(g, out) == std::string(out, 'a'));  // exactly at the limit
  bool caught = false;
  try {
    gunzip(g, uint64_t{1} << 20);
  } catch (const GzipError& e) {
    caught = std::string(e.what()).find("limit") != std::string::npos;
  }
  CHECK(caught);
  // Files: the process-wide limit, with the path in the error (also through the MPS reader).
  const auto p = std::filesystem::temp_directory_path() / "milp_test_gzip_bomb.mps.gz";
  write_file(p, g);
  CHECK(read_maybe_gzipped_file(p.string()).size() == out);
  set_gzip_max_output(uint64_t{1} << 20);
  CHECK(gzip_max_output() == uint64_t{1} << 20);
  caught = false;
  try {
    read_maybe_gzipped_file(p.string());
  } catch (const GzipError& e) {
    const std::string w = e.what();
    caught = w.find("milp_test_gzip_bomb") != std::string::npos && w.find("limit") != std::string::npos;
  }
  CHECK(caught);
  caught = false;
  try {
    read_mps(p.string());
  } catch (const MpsError& e) {
    caught = std::string(e.what()).find("limit") != std::string::npos;
  }
  CHECK(caught);
  set_gzip_max_output(0);  // back to the default
  CHECK(gzip_max_output() == kDefaultGzipMaxOutput);
  std::filesystem::remove(p);
}
